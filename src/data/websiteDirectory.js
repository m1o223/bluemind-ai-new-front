export function createLiveWebsiteResults(query) {
  const normalized = String(query || "").trim().toLowerCase();
  if (!normalized) return [];

  const slug = normalized
    .replace(/https?:\/\//g, "")
    .replace(/[^a-z0-9åäöüéèñ\s.-]/gi, " ")
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 3)
    .join("-");

  if (!slug) return [];

  const readable = normalized
    .split(/\s+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");

  return [
    normalizeSite([`${readable} official website`, `${slug}.com`, "Technology", "USA", "Live web lookup suggestion based on your search."]),
    normalizeSite([`${readable} search on Google`, `www.google.com/search?q=${encodeURIComponent(normalized)}`, "Technology", "USA", "Search the web for official websites and related results."]),
    normalizeSite([`${readable} search on DuckDuckGo`, `duckduckgo.com/?q=${encodeURIComponent(normalized)}`, "Technology", "USA", "Privacy-focused live web search for this query."]),
  ];
}
