function normalizeSite([name, domain, category, country = "USA", description]) {
  const url = domain.startsWith("http") ? domain : `https://${domain}`;
  const normalizedDomain = domain.replace(/^https?:\/\//, "").replace(/\/$/, "");
  const primaryCategory = country === "Sweden" ? "Sweden" : category;

  return {
    id: `${name}-${normalizedDomain}`.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, ""),
    name,
    domain: normalizedDomain,
    url,
    category,
    primaryCategory,
    country,
    countryBadge: countryBadge(country),
    description: description || CATEGORY_DESCRIPTIONS[category] || "Explore this website and its official content.",
    logo: websiteLogoUrl(normalizedDomain),
    tags: [name, domain, category, country, primaryCategory].join(" ").toLowerCase(),
  };
}

function uniqueByDomain(sites) {
  const seen = new Set();
  return sites.filter((site) => {
    if (seen.has(site.domain)) return false;
    seen.add(site.domain);
    return true;
  });
}

